#include <stdlib.h>
#include <stdio.h>
#include <unistd.h>
#include <string.h>

int	ft_is_alphanum(char c)
{
	if (c >= 'a' && c <= 'z')
	{
		return (1);
	}
	else if (c >= 'A' && c <= 'Z')
	{
		return (1);
	}
	else if (c >= '0' && c <= '9')
	{
		return (1);
	}
	return (0);
}

int	ft_is_maj(char c)
{
	if (c >= 'A' && c <= 'Z')
	{
		return (1);
	}
	return (0);
}

char	*ft_strcapitalize(char *str)
{
	int	i;

	i = 0;
	while (str[i])
	{
		if (i == 0 || ft_is_alphanum(str[i - 1]) == 0)
		{
			if (str[i] >= 'a' && str[i] <= 'z')
				str[i] = str[i] - 32;
		}
		else if (ft_is_maj(str[i]))
		{
			str[i] = str[i] + 32;
		}
		i++;
	}
	return (str);
}

